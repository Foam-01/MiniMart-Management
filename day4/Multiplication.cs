using System;

namespace TestConsole.day4
{
    public class Multiplication
    {
        public static void Run()
        {
            Console.OutputEncoding = System.Text.Encoding.UTF8; // รองรับภาษาไทยและเส้นตารางบน Console

            Console.WriteLine("\n========================================================================================");
            Console.WriteLine("                                👑 ตารางสูตรคูณ แม่ 1 - 12 👑                                ");
            Console.WriteLine("========================================================================================");

            // วนลูปตัวคูณจาก 1 ถึง 12 (แนวตั้ง)
            for (int j = 1; j <= 12; j++)
            {
                // วนลูปแม่สูตรคูณจาก 1 ถึง 12 (แนวนอน)
                for (int i = 1; i <= 12; i++)
                {
                    // ใช้ {0,-7} เพื่อล็อกความกว้างไว้ 7 ตัวอักษรชิดซ้าย ทำให้ตารางตรงกันเป๊ะทุกคอลัมน์
                    string result = $"{i}x{j}={i * j}";
                    Console.Write("{0,-8}", result);
                }
                Console.WriteLine(); // ขึ้นบรรทัดใหม่เมื่อพิมพ์ครบทุกแม่ในแถวนั้นๆ

                // ตกแต่งเส้นคั่นระหว่างบรรทัดเพื่อความสมบูรณ์แบบ
                if (j == 1 || j == 12)
                {
                    Console.WriteLine("----------------------------------------------------------------------------------------");
                }
            }
            Console.WriteLine();
        }
    }
}